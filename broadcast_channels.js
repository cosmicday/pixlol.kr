// 방송 탭 — 유튜브 채널 손 명단 (2026-09-17)
//
// 유튜브는 「지금 롤 방송 중인 채널」을 API 로 거를 수 없어서, 명단을 두고 그 채널들만 확인한다.
// 명단 대부분은 서버가 `롤` 검색에서 **자동으로** 모은다 (DB `ytchannels`). 여기는 손으로 고칠 것만 적는다.
//
//   include — 자동으로 안 잡혀도 **항상** 확인할 채널
//   exclude — 자동으로 잡혀도 **절대** 안 보여 줄 채널 (롤이 아닌 방송·재방송 채널 등)
//
// ★ 값은 채널 ID(`UC` 로 시작하는 24자)다. 채널 주소가 `/@이름` 꼴이면 그 페이지 소스에서
//   `"channelId":"UC…"` 를 찾으면 된다. 이름은 알아보기 위한 메모일 뿐 코드가 안 쓴다.
// ★ 고치고 push 하면 다음 배포부터 반영된다.
module.exports = {
    include: [
        // { id: 'UCxxxxxxxxxxxxxxxxxxxxxx', name: '방송인 이름' },
    ],
    exclude: [
        // { id: 'UCxxxxxxxxxxxxxxxxxxxxxx', name: '롤이 아닌 채널' },
    ]
};
